),
normalized AS (
  SELECT
    filename,
    '/product-images/' || filename AS image_url,
    lower(regexp_replace(filename, '\\.[^.]+$', '', 'g')) AS base_slug,
    trim(regexp_replace(replace(regexp_replace(filename, '\\.[^.]+$', '', 'g'), '-', ' '), '\\s+', ' ', 'g')) AS inferred_name,
    (('x' || substr(md5(filename), 1, 8))::bit(32)::bigint) AS seed_num
  FROM source_files
),
classified AS (
  SELECT
    ('img-' || substr(md5(filename), 1, 24)) AS id,
    (base_slug || '-' || substr(md5(filename), 1, 6)) AS slug,
    inferred_name AS name,
    inferred_name AS name_ar,
    image_url,
    seed_num,
    CASE
      WHEN lower(filename) ~ '(كريم|سيروم|شامبو|لوشن|ماسكارا|مكياج|عطر|تبييض|قناع|الوجه|البشرة|الشعر|حواجب|رموش|تونر|تقشير|retinol|niacinamide|eucerin|k18|flawless|facial|scrub|hair|papaya|kojic|v10|sheglam|ساكورا|نيزورال|أكريتين|هاي-كوين|سم-النحل|مخاط-الحلزون|wart)' THEN 'beauty'
      WHEN lower(filename) ~ '(فيتامين|حبوب|كيتو|ميلاتونين|مغنيزيوم|اشواغاندا|البروبيوتيك|قهوة-خضراء|الزنجبيل|السمك|biotin|omega|glucosamine|supplement|قولون|أقراص|علكات|شاي-علاجي|السنا|عرق-السوس)' THEN 'supplements'
      WHEN lower(filename) ~ '(تدليك|دعامة|الركبة|العنق|ظهر|القدمين|السمع|ضغط|مفاصل|الأسنان|للحكة|فطرية|مساج|ems|تنفس|السكري|القرحة|ألم|البواسير|الندبات|تقويم|تصحيح|مصحح|حقيبة-جمع-البول|البروستاتا)' THEN 'personal'
      WHEN lower(filename) ~ '(أطفال|الاطفال|رضع|لعبة|خيمة-لعب|حظيرة-للعب|مجموعة-ملاكمة-للأطفال|سجادات-صلاة-للأطفال|درج-المرحاض-للاطفال|مدفأة-زجاجات-الأطفال|لوحة-تعلم|سيارة-بهلوانية|طائرة-هليكوبتر|طائرة-مقاتلة)' THEN 'kids'
      WHEN lower(filename) ~ '(كاميرا|بلوتوث|واي-فاي|usb|led|مكبر-صوت|سماعة|جهاز-عرض|تحكم|lcd|جالاكسي|مصباح-led|نظارات-شمسية-بلوتوث|إرسال-واستقبال-فيديو|مروحة-توربو|وحدة-تحكم-ألعاب)' THEN 'smart'
      WHEN lower(filename) ~ '(مطبخ|ممسحة|دلو|خلاط|عصارة|قطاعة|رف-المطبخ|خزانة|منظم|مكنسة|موقد|خرطوم|سكاكين|ملعقة|ميزان|موزع|معجون|صندوق-غداء|مضخة-مياه|طاولة|كرسي|ولاعة|فوهة|فلتر|غاز|ختم-الأكياس|قوالب-الزلابية|دش|المرحاض|كشاف|سجاد|مروحة|المصباح|خلاط-فواكه|كوب-قهوة|خزنة-كتب|حامل-غسالة|مناديل-إزالة-البقع|مكيف|تنظيف-الصرف|مجفف-الأحذية|شنطة-مفك-كهربائي)' THEN 'home'
      ELSE 'various'
    END AS category_id
  FROM normalized
),
priced AS (
  SELECT
    id,
    slug,
    name,
    name_ar,
    image_url,
    category_id,
    seed_num,
    CASE
      WHEN category_id = 'supplements' THEN (45 + (seed_num % 140))::numeric(10,2)
      WHEN category_id = 'beauty' THEN (55 + (seed_num % 230))::numeric(10,2)
      WHEN category_id = 'personal' THEN (65 + (seed_num % 260))::numeric(10,2)
      WHEN category_id = 'home' THEN (70 + (seed_num % 320))::numeric(10,2)
      WHEN category_id = 'smart' THEN (95 + (seed_num % 420))::numeric(10,2)
      WHEN category_id = 'kids' THEN (50 + (seed_num % 220))::numeric(10,2)
      ELSE (60 + (seed_num % 260))::numeric(10,2)
    END AS price,
    CASE
      WHEN category_id = 'beauty' THEN 'منتج عناية مختار بعناية وجودة مناسبة للاستخدام اليومي.'
      WHEN category_id = 'supplements' THEN 'مكمل غذائي داعم للصحة العامة ضمن الاستخدام اليومي.'
      WHEN category_id = 'personal' THEN 'منتج للعناية الشخصية والراحة اليومية.'
      WHEN category_id = 'home' THEN 'منتج عملي للمنزل والمطبخ والاستخدام اليومي.'
      WHEN category_id = 'smart' THEN 'جهاز أو ملحق تقني عملي للاستخدام اليومي.'
      WHEN category_id = 'kids' THEN 'منتج مخصص للأطفال للاستخدام المنزلي.'
      ELSE 'منتج متنوع للاستخدام اليومي.'
    END AS description_ar
  FROM classified
),
final_rows AS (
  SELECT
    id,
    slug,
    name,
    name_ar,
    description_ar,
    price,
    round((price * (1.20 + ((seed_num % 26)::numeric / 100))), 2)::numeric(10,2) AS compare_at_price,
    image_url,
    ARRAY[image_url]::text[] AS images,
    category_id,
    (6 + (seed_num % 45))::integer AS stock,
    (seed_num % 9 = 0) AS featured,
    true AS active,
    CASE
      WHEN seed_num % 7 = 0 THEN 'الأكثر طلباً'
      WHEN seed_num % 5 = 0 THEN 'عرض'
      WHEN seed_num % 3 = 0 THEN 'جديد'
      ELSE NULL
    END AS badge,
    (4.2 + ((seed_num % 8)::numeric / 10))::numeric(3,1) AS rating
  FROM priced
),
deduped AS (
  SELECT f.*
  FROM final_rows f
  WHERE NOT EXISTS (
    SELECT 1
    FROM products p
    WHERE lower(trim(leading '/' FROM coalesce(p.image_url, ''))) = lower(trim(leading '/' FROM f.image_url))
       OR lower(coalesce(p.slug, '')) = lower(f.slug)
       OR lower(coalesce(p.name_ar, '')) = lower(f.name_ar)
  )
),
inserted AS (
  INSERT INTO products (
    id,
    slug,
    name,
    name_ar,
    description,
    description_ar,
    price,
    compare_at_price,
    image_url,
    images,
    category_id,
    stock,
    featured,
    active,
    badge,
    rating,
    created_at,
    updated_at
  )
  SELECT
    id,
    slug,
    name,
    name_ar,
    description_ar,
    description_ar,
    price,
    compare_at_price,
    image_url,
    images,
    category_id,
    stock,
    featured,
    active,
    badge,
    rating,
    now(),
    now()
  FROM deduped
  ON CONFLICT (id) DO NOTHING
  RETURNING id
)
SELECT count(*) AS inserted_count FROM inserted;

